/** Sign in (or register) the caller with a chosen username. */
export function useSignIn() {
  const { actor } = useActor(createActor);
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async (username: string): Promise<UserProfile> => {
      if (!actor) throw new Error("Backend actor not ready");
      return actor.signIn(username);
    },
    onSuccess: () => {
      void queryClient.invalidateQueries({ queryKey: queryKeys.profile });
      void queryClient.invalidateQueries({ queryKey: COINS_QUERY_KEY });
      void queryClient.invalidateQueries({ queryKey: STREAK_QUERY_KEY });
    },
  });
}

