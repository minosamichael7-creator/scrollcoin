/**
 * Centralized React Query hooks for every backend actor method.
 *
 * Page tasks import the named hooks from here instead of calling the actor
 * directly, so query keys, enabled-guards, and guest fallbacks stay
 * consistent across the app. Mutations invalidate the relevant query keys so
 * the coin balance and feed stay fresh after awards and redemptions.
 */
import { createActor } from "@/backend";
import { COINS_QUERY_KEY } from "@/hooks/useCoins";
import { STREAK_QUERY_KEY } from "@/hooks/useStreak";
import type {
  Achievement,
  CoinAward,
  DailyGoal,
  Ebook,
  FeedContent,
  LeaderboardEntry,
  Lesson,
  Product,
  ProductRedemption,
  Redemption,
  RewardItem,
  UserProfile,
} from "@/types/rewards";
import { useActor } from "@caffeineai/core-infrastructure";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";

/** Query keys are colocated here so mutations can invalidate them. */
export const queryKeys = {
  profile: ["profile"] as const,
  feed: (offset: bigint, limit: bigint, category?: string) =>
    ["feed", offset.toString(), limit.toString(), category ?? "all"] as const,
  rewards: ["rewards"] as const,
  leaderboard: ["leaderboard"] as const,
  achievements: ["achievements"] as const,
  earningsHistory: ["earningsHistory"] as const,
  dailyGoal: (date: bigint) => ["dailyGoal", date.toString()] as const,
  products: (offset: bigint, limit: bigint) =>
    ["products", offset.toString(), limit.toString()] as const,
  product: (id: bigint) => ["product", id.toString()] as const,
  ebooks: (offset: bigint, limit: bigint) =>
    ["ebooks", offset.toString(), limit.toString()] as const,
  ebook: (id: bigint) => ["ebook", id.toString()] as const,
  lessons: (offset: bigint, limit: bigint) =>
    ["lessons", offset.toString(), limit.toString()] as const,
  lesson: (id: bigint) => ["lesson", id.toString()] as const,
};

const EMPTY: readonly never[] = [];

/** Profile of the signed-in caller (or `null` for guests). */
export function useProfile() {
  const { actor, isFetching } = useActor(createActor);
  return useQuery({
    queryKey: queryKeys.profile,
    queryFn: async (): Promise<UserProfile | null> => {
      if (!actor) return null;
      return actor.getProfile();
    },
    enabled: !isFetching,
  });
}

/** Paginated feed content for the endless scroll.
 *
 * `category` is an optional server-side filter. When omitted (or `"all"`),
 * the backend returns content across all categories. When provided (e.g.
 * `"finance"`), the backend narrows the slice to that category. The backend
 * `getFeedContent(offset, limit, category?)` signature is regenerated by
 * bindgen during the check wave; until then the third argument is forwarded
 * and the actor accepts it once the bindings are refreshed.
 */
export function useFeedContent(
  offset: bigint,
  limit: bigint,
  category?: string,
) {
  const { actor, isFetching } = useActor(createActor);
  const normalized = category && category !== "all" ? category : undefined;
  return useQuery({
    queryKey: queryKeys.feed(offset, limit, normalized),
    queryFn: async (): Promise<FeedContent[]> => {
      if (!actor) return [];
      if (normalized) {
        return actor.getFeedContent(offset, limit, normalized);
      }
      return actor.getFeedContent(offset, limit, null);
    },
    enabled: !isFetching,
  });
}

