/** Award coins for a scroll milestone. Invalidates wallet + streak. */
export function useRecordScrollMilestone() {
  const { actor } = useActor(createActor);
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async (args: { sessionId: bigint; milestone: bigint }) => {
      if (!actor) throw new Error("Backend actor not ready");
      return actor.recordScrollMilestone(args.sessionId, args.milestone);
    },
    onSuccess: () => {
      void queryClient.invalidateQueries({ queryKey: COINS_QUERY_KEY });
      void queryClient.invalidateQueries({ queryKey: STREAK_QUERY_KEY });
      void queryClient.invalidateQueries({
        queryKey: queryKeys.earningsHistory,
      });
      // Milestone awards contribute to the daily goal, so invalidate every
      // dailyGoal entry (prefix match) to refresh the progress bar.
      void queryClient.invalidateQueries({
        queryKey: ["dailyGoal"],
      });
    },
  });
}

/** Redeem a reward by id. Invalidates wallet + rewards on success. */
export function useRedeemReward() {
  const { actor } = useActor(createActor);
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async (rewardId: bigint): Promise<Redemption> => {
      if (!actor) throw new Error("Backend actor not ready");
      const result = await actor.redeemReward(rewardId);
      if (result.__kind__ === "err") {
        throw new Error(result.err);
      }
      return result.ok;
    },
    onSuccess: () => {
      void queryClient.invalidateQueries({ queryKey: COINS_QUERY_KEY });
      void queryClient.invalidateQueries({ queryKey: queryKeys.rewards });
    },
  });
}

